#!/usr/bin/env python3
"""gen_digests — ON-DEMAND generator for the two rollup digests (action-items, decisions).

These were formerly regenerated + committed on every `check.sh` run (via `regen.regen_digests`).
By design: their git history is
not used as an audit trail — only the current snapshot matters — so they are no longer committed.
Generate them live, the same way `scripts/engram_brief.py` produces its output on demand.

The note-reading primitives (`fm`, `notes_in`, `mdlink`) and the domain list stay owned by
`regen.py`; the `## <section>` extractor stays owned by `_lib.notes.section`. This module owns only
the digest-assembly logic (moved verbatim out of the retired `regen.regen_digests`), so there is one
owner per decision.

    python3 scripts/gen_digests.py                 # (re)write digests/action-items.md + digests/decisions.md
    python3 scripts/gen_digests.py --stdout        # print to stdout, write nothing
    python3 scripts/gen_digests.py --which decisions
    python3 scripts/gen_digests.py --out /tmp/d    # write to a different directory

Importable: `collect_rows()`, `render_action_items(rows)`, `render_decisions(rows)`, `write(out_dir)`.
All corpus reads are cwd-relative (like regen), so the CLI chdir's to the repo root first; importers
that call `write()`/`collect_rows()` must already be at the repo root (the profile scripts, the only
current consumers, chdir there themselves).
"""
import argparse
import collections
import os
import sys
import tempfile

_ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, os.path.join(_ROOT, "scripts"))
import regen  # noqa: E402  — reuse fm/notes_in/mdlink/TOPS (single owner of those primitives)
from _lib.notes import section  # noqa: E402  — single owner of `## <name>` extraction

_PROV = "scripts/gen_digests.py"  # provenance shown in the generated header


def collect_rows(tops=None):
    """One dict per note across all domains: fm() fields + dom/fp + extracted actions/decisions.
    Reverse-chron by (date, fp) — fp is a stable tiebreaker within a date. cwd must be the repo root
    (regen.notes_in globs cwd-relative). Moved verbatim from regen.regen_digests."""
    tops = regen.TOPS if tops is None else tops
    rows = []
    for dom in tops:
        for fp in regen.notes_in(dom):
            m = regen.fm(fp)
            m["dom"] = dom
            m["fp"] = fp
            m["actions"] = section(m["body"], "Action items")
            m["decisions"] = section(m["body"], "Decisions")
            rows.append(m)
    rows.sort(key=lambda n: (n["date"], n["fp"]), reverse=True)
    return rows


def _lk(n):
    return regen.mdlink(n["title"] or os.path.basename(n["fp"]), n["fp"])


def render_action_items(rows):
    """`## Action items` rollup, grouped by domain, reverse-chron — byte-for-byte the old
    regen.regen_digests layout (only the provenance line names the new owner)."""
    bd = collections.defaultdict(list)
    for n in rows:
        if n["actions"]:
            bd[n["dom"]].append(n)
    out = ["# Action-items rollup\n",
           f"_Generated by {_PROV} from every `## Action items` section, by domain, reverse-chron._\n",
           f"\n{sum(len(v) for v in bd.values())} notes.\n"]
    for dom in sorted(bd):
        out.append(f"\n## {dom} ({len(bd[dom])})\n")
        for n in bd[dom]:
            out.append(f"\n### {n['date']} · {_lk(n)}")
            out += n["actions"]
    return "\n".join(out) + "\n"


def render_decisions(rows):
    """`## Decisions` log, reverse-chron — byte-for-byte the old regen.regen_digests layout
    (only the provenance line names the new owner)."""
    out = ["# Decisions log\n",
           f"_Generated by {_PROV} from every `## Decisions` section, reverse-chron._\n",
           f"\n{sum(1 for n in rows if n['decisions'])} notes.\n"]
    for n in rows:
        if not n["decisions"]:
            continue
        out.append(f"\n### {n['date']} · [{n['dom']}] · {_lk(n)}")
        out += n["decisions"]
    return "\n".join(out) + "\n"


def _atomic_write(path, text):
    d = os.path.dirname(path) or "."
    fd, tmp = tempfile.mkstemp(dir=d, prefix=".gen_digests.", suffix=".tmp")
    try:
        with os.fdopen(fd, "w", encoding="utf-8") as f:
            f.write(text)
        os.replace(tmp, path)
    finally:
        if os.path.exists(tmp):
            os.remove(tmp)


def write(out_dir="digests", rows=None, which="both"):
    """Regenerate the digest file(s) under out_dir. Returns the list of paths written."""
    if rows is None:
        rows = collect_rows()
    os.makedirs(out_dir, exist_ok=True)
    written = []
    if which in ("both", "action-items"):
        p = os.path.join(out_dir, "action-items.md")
        _atomic_write(p, render_action_items(rows))
        written.append(p)
    if which in ("both", "decisions"):
        p = os.path.join(out_dir, "decisions.md")
        _atomic_write(p, render_decisions(rows))
        written.append(p)
    return written


def main():
    ap = argparse.ArgumentParser(description="On-demand generator for the action-items / decisions digests.")
    ap.add_argument("--out", default="digests", help="output directory (default: digests/)")
    ap.add_argument("--which", choices=["both", "action-items", "decisions"], default="both")
    ap.add_argument("--stdout", action="store_true", help="print to stdout, write no files")
    a = ap.parse_args()
    os.chdir(_ROOT)
    rows = collect_rows()
    if a.stdout:
        parts = []
        if a.which in ("both", "action-items"):
            parts.append(render_action_items(rows))
        if a.which in ("both", "decisions"):
            parts.append(render_decisions(rows))
        sys.stdout.write("\n".join(parts))
        return
    written = write(a.out, rows=rows, which=a.which)
    for p in written:
        print(f"wrote {p}")


if __name__ == "__main__":
    main()

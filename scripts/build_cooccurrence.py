#!/usr/bin/env python3
"""Build a people co-occurrence index from note `participants` — a SECOND-TIER, LOW-PRECISION
relationship graph that complements the hand-authored `related:` links.

    python3 scripts/build_cooccurrence.py

Emits _manifest/co-occurrence.md: for each recurring person, who they most often appear with,
their domain spread, and meeting count. This is a WEAK SIGNAL — "consider", never auto-merge,
never asserted as fact (entity-resolution discipline). Two uses:
  - relationship discovery ("who works with X?") that grep over prose can't rank.
  - a dedup aid: two name-variants that share the same co-occurrence neighbourhood are likely
    the same person (cross-check for `/clarify` people-dedup answers).

Reads _manifest/index.jsonl if present (fast), else parses notes. Deterministic.
"""
import re, glob, os, json, collections, sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
os.chdir(ROOT)
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from _lib.constants import DOMAINS as TOPS
from _lib.actions import self_aliases   # single owner of "who is the store owner" (people.md self row)

# A participant who appears in nearly every note carries no information as a co-occurrence edge, so
# the store owner (the `self` row of _manifest/people.md, if there is one) is dropped from both the
# people list and every neighbour list. No self row -> nothing is dropped, which is the right
# default for a multi-user store with no single dominant participant.


def load_notes():
    idx = "_manifest/index.jsonl"
    if os.path.exists(idx):
        return [json.loads(l) for l in open(idx, encoding="utf-8") if l.strip()]
    # fallback: parse frontmatter directly
    out = []
    for fp in (f for d in TOPS for f in glob.glob(f"{d}/**/*.md", recursive=True)
               if not f.endswith("_index.md")):
        head = open(fp, encoding="utf-8").read()
        head = head[:head.index("\n---", 3)] if "\n---" in head[3:] else head
        pm = re.search(r'^participants:\s*\[(.*?)\]', head, re.M)
        dm = re.search(r'^domain:\s*(\S+)', head, re.M)
        parts = [x.strip().strip('"') for x in pm.group(1).split(",")] if pm else []
        out.append(dict(participants=[p for p in parts if p], domain=dm.group(1) if dm else ""))
    return out


def main():
    notes = load_notes()
    meetings = collections.Counter()
    domains = collections.defaultdict(collections.Counter)
    pair = collections.defaultdict(collections.Counter)
    for n in notes:
        ppl = [p for p in n.get("participants", []) if p]
        for p in ppl:
            meetings[p] += 1
            if n.get("domain"):
                domains[p][n["domain"]] += 1
        for i, a in enumerate(ppl):
            for b in ppl[i + 1:]:
                if a == b:
                    continue
                pair[a][b] += 1
                pair[b][a] += 1

    selves = self_aliases(ROOT)
    people = sorted((p for p in meetings if p.lower() not in selves),
                    key=lambda p: (-meetings[p], p.lower()))
    out = ["# engram — people co-occurrence (generated, weak signal)\n",
           "_Generated by `scripts/build_cooccurrence.py` from note `participants`. A **low-"
           "precision** relationship graph: ranks candidates, **never auto-merges, never asserts "
           "fact**. Use as a discovery aid and a `/clarify` dedup cross-check. The store owner "
           "(people.md `self` row) is omitted from edges — they appear in nearly every note._\n",
           f"\n**{len(people)} people across {len(notes)} notes.**\n"]
    for p in people:
        if meetings[p] < 2:
            continue
        doms = ", ".join(f"{d}×{c}" for d, c in domains[p].most_common(3))
        top = ", ".join(f"{q} ({c})" for q, c in pair[p].most_common(6) if q.lower() not in selves)
        out.append(f"\n**{p}** — {meetings[p]} mtgs · {doms}")
        out.append(f"- with: {top}" if top else "- with: —")
    open("_manifest/co-occurrence.md", "w", encoding="utf-8").write("\n".join(out) + "\n")
    print(f"co-occurrence: {len(people)} people -> _manifest/co-occurrence.md")


if __name__ == "__main__":
    main()
